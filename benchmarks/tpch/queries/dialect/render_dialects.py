"""Deterministic canonical -> per-engine dialect generator.

Reads the 22 standard TPC-H queries from `queries/tpch_canonical/` (the
official text, as rendered by DuckDB's own `tpch` extension — including its
CTE form of Q15, used in place of the spec's `CREATE VIEW`/`DROP VIEW` pair
since CTEs behave identically across all three engines and views don't) and
writes one copy per engine under `queries/dialect/<engine>/`.

Every file written here is a mechanical copy of its canonical source with
zero or more declared `OVERRIDES` applied — never hand-edited. That keeps
"what changed for this engine and why" fully in this module and in the
`DIFFS.md` it generates, rather than silently drifting file by file.

`OVERRIDES` starts empty: no dialect incompatibility has been observed yet.
Phase 0 (plan §6) runs the unmodified canonical text against live Snowflake
and Databricks accounts; add an entry here only once a real failure is
observed there, never speculatively — see plan §4's impartiality rule that
translations must be minimal and logged, not anticipatory tuning.
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass
from pathlib import Path

# markdownlint's default MD013 line-length limit, which DIFFS.md's prose
# lines (table rows are exempt) must stay under like every other committed
# markdown file in the repo.
_MD_LINE_WIDTH = 80

_QUERIES_DIR = Path(__file__).resolve().parent.parent
_CANONICAL_DIR = _QUERIES_DIR / "tpch_canonical"
_DIALECT_DIR = Path(__file__).resolve().parent
_ENGINES = ("duckhaven", "snowflake", "databricks")


@dataclass(frozen=True)
class Override:
    engine: str
    query_nr: str  # zero-padded, e.g. "01"
    find: str
    replace: str
    reason: str


OVERRIDES: tuple[Override, ...] = (
    # Confirmed by a real syntax error during Phase 0's Snowflake dry run
    # (SF1, sequential scenario): Snowflake does not accept the SQL-standard
    # `SUBSTRING(x FROM start FOR length)` form DuckDB's tpch extension
    # renders Q22 with. All three occurrences in Q22 are this exact
    # substring; Snowflake's function-call form is equivalent for it (no
    # negative/omitted-length edge cases in this query to worry about).
    Override(
        engine="snowflake",
        query_nr="22",
        find="substring(c_phone FROM 1 FOR 2)",
        replace="SUBSTR(c_phone, 1, 2)",
        reason="Snowflake rejects SQL-standard SUBSTRING(x FROM .. FOR ..); "
        "confirmed via a live 001003 syntax error, Phase 0 SF1 dry run.",
    ),
)


def render() -> dict[str, list[str]]:
    """Write dialect/<engine>/qNN.sql for every canonical query and engine.

    Returns {engine: [query_nr, ...]} for each query an override touched,
    in canonical order, for `diffs_md` to report on.
    """
    canonical_files = sorted(_CANONICAL_DIR.glob("q*.sql"))
    changed: dict[str, list[str]] = {engine: [] for engine in _ENGINES}
    for engine in _ENGINES:
        engine_dir = _DIALECT_DIR / engine
        engine_dir.mkdir(parents=True, exist_ok=True)
        for path in canonical_files:
            query_nr = path.stem.removeprefix("q")
            text = path.read_text()
            for override in OVERRIDES:
                if override.engine != engine or override.query_nr != query_nr:
                    continue
                if override.find not in text:
                    raise ValueError(
                        f"{engine}/q{query_nr}: override text not found in the "
                        f"canonical query ({override.reason!r}) — the canonical "
                        "query changed underneath a stale override"
                    )
                text = text.replace(override.find, override.replace)
                changed[engine].append(query_nr)
            (engine_dir / path.name).write_text(text)
    return changed


def diffs_md(changed: dict[str, list[str]]) -> str:
    lines = [
        "# Dialect differences",
        "",
        textwrap.fill(
            "One row per query that needed a change from the canonical TPC-H "
            "text (`queries/tpch_canonical/`) to run on a given engine. "
            "Generated by `render_dialects.py` from its `OVERRIDES` table — "
            "do not hand-edit.",
            width=_MD_LINE_WIDTH,
        ),
        "",
    ]
    rows = [
        (engine, override)
        for engine in _ENGINES
        for override in OVERRIDES
        if override.engine == engine
    ]
    if not rows:
        lines.append(
            textwrap.fill(
                "No overrides are declared. All 22 canonical queries run "
                "unmodified on every engine as of the last render.",
                width=_MD_LINE_WIDTH,
            )
        )
    else:
        lines += [
            "| Engine | Query | Change | Reason |",
            "|---|---|---|---|",
        ]
        for engine, override in rows:
            lines.append(
                f"| {engine} | Q{override.query_nr} | "
                f"`{override.find}` -> `{override.replace}` | {override.reason} |"
            )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    changed = render()
    (_DIALECT_DIR / "DIFFS.md").write_text(diffs_md(changed))
    total = sum(len(v) for v in changed.values())
    n_canonical = len(list(_CANONICAL_DIR.glob("q*.sql")))
    print(
        f"Rendered {len(_ENGINES)} dialect(s) from {n_canonical} canonical "
        f"queries ({total} override(s) applied)."
    )


if __name__ == "__main__":
    main()
